def render_html(report: dict[str, Any], extras: dict[str, Any] | None = None) -> str:
    """Render the report dict to an HTML string. ``extras`` may add endpoints/
    technologies/counts pulled from storage or the scan context."""
    extras = extras or {}
    target = report.get("target") or {}
    scope = (report.get("config") or {}).get("scope") or {}
    risk = report.get("risk") or {}
    endpoints = extras.get("endpoints", [])
    technologies = extras.get("technologies", report.get("technologies", []))
    counts = {
        "pages": extras.get("pages_count", 0),
        "assets": extras.get("assets_count", 0),
        "endpoints": len(endpoints),
        "technologies": len(technologies),
    }
    template = _env.from_string(_TEMPLATE)
    return template.render(
        version=__version__,
        scan_id=report.get("scan_id", ""),
        target_url=target.get("base_url") or target.get("input_url") or "unknown target",
        target_host=target.get("hostname", "unknown"),
        risk_level=(risk.get("level") if risk else None) or "informational",
        summary=report.get("summary", {"total_findings": 0, "by_severity": {}}),
        scope={"mode": scope.get("mode", "same-domain"),
               "max_depth": scope.get("max_depth", "-"),
               "max_pages": scope.get("max_pages", "-")},
        findings=report.get("findings", []),
        technologies=technologies,
        endpoints=endpoints,
        counts=counts,
        ip_intel=extras.get("ip_intel") or report.get("ip_intel"),
        intel=report.get("intelligence") or extras.get("intelligence"),
    )
